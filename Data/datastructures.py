coordinates = (10,20)

#SET - UNIQUE ITEMS Only, No Duplicates!
colours = {"cyan","green","orange"}

#Print score
print("Scores",scores)

#print student
print("StudentInfo",student)

#print coordinates
print("coordinates",coordinates)

#Print Colours
print("Colours",colours)

